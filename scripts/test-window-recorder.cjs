const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { createWindowRecorder } = require('../electron/windowRecorder.cjs')
const base = path.join(__dirname, '..', '.private')
fs.mkdirSync(base, { recursive: true })
const directory = fs.mkdtempSync(path.join(base, 'recorder-test-'))
let at = new Date(2026, 9, 28, 9).getTime()
const recorder = createWindowRecorder({ directory, now: () => at })
for (let i = 0; i <= 30; i++) {
  recorder.tick(at)
  recorder.observe({ app: 'Code.exe', title: 'first' }, at)
  at += 1000
}
assert.equal(recorder.batch().find(event => event.data.kind === 'work-session').duration, 30, 'records without renderer or acknowledgements')
recorder.pause(at)
const locked = recorder.batch().map(event => JSON.stringify(event))
at += 60000
recorder.tick(at)
recorder.observe({ app: 'Code.exe', title: 'locked' }, at)
assert.deepEqual(recorder.batch().map(event => JSON.stringify(event)), locked, 'locked time creates no events')
recorder.resume()
recorder.tick(at)
recorder.observe({ app: 'Chrome.exe', title: 'resumed' }, at)
at += 2000
recorder.tick(at)
recorder.observe({ app: 'Chrome.exe', title: 'resumed' }, at)
const sessions = recorder.batch().filter(event => event.data.kind === 'work-session')
assert.equal(sessions.length, 2)
assert.equal(sessions[1].duration, 2)
const reopened = createWindowRecorder({ directory })
assert.equal(reopened.batch().length, recorder.batch().length, 'unacknowledged records survive process restart')
const outdated = { ...sessions[1], duration: 0 }
recorder.acknowledge([outdated])
assert.ok(recorder.batch().some(event => event.id === outdated.id), 'stale acknowledgement cannot discard newer duration')
recorder.acknowledge(recorder.batch())
assert.equal(recorder.batch().length, 0)
at = new Date(2026, 9, 28, 23, 59, 59).getTime()
recorder.reset()
recorder.tick(at)
at += 2000
recorder.tick(at)
assert.equal(recorder.batch().filter(event => event.data.kind === 'work-session').reduce((sum, event) => sum + event.duration, 0), 2, 'midnight splits without missing or duplicating time')
console.log('PASS: renderer-independent recording, lock exclusion, resume, durable replay, safe acknowledgement and midnight split')
